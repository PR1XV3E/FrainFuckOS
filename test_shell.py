"""Integration checks against the actual BIOS workstation and data disk."""
import tempfile
from pathlib import Path
from disk import entries, initialize, put
from raw_test_support import Machine, ROOT

def content(image, name):
    return next(item[2] for item in entries(image.read_bytes()) if item[1] == name)

with tempfile.TemporaryDirectory() as directory:
    image = Path(directory) / "data.img"
    initialize(image)
    put(image, "broken.bf", b"[+")
    put(image, "busy.bf", b"+[]")
    put(image, "crlf.txt", b"first\r\nsecond\r\n")
    put(image, "full.txt", b"x" * 2047)
    put(image, "nested.bf", b"++++[>++[>++++++++<-]<-]>>.")
    put(image, "wrap.bf", b"<" + b"+"*65 + b".>" + b"+"*66 + b"." + b"+"*255 + b".")
    with Machine(image) as m:
        def check(command, expected):
            m.line("clear")
            m.line(command)
            return m.wait_for(expected,timeout=60)
        check("ls", "readme.txt")
        check("calc 12*7", "84")
        check("calc 65535+1", "no overflow")
        check("calc 1/0", "no overflow")
        check("calc 100-1", "99")
        check("calc 100/3", "33")
        check("calc 65535", "no overflow")
        check("versionx", "Unknown command")
        check("cat missing.txt", "File not found")
        check("edit ../x", "Name: 1..15")
        check("cat crlf.txt", "second")
        rows = m.screen().splitlines()
        first = next(i for i, row in enumerate(rows) if "first" in row)
        assert "second" in rows[first+1]
        check("time", "BFOS>")
        check("date", "BFOS>")
        check("mem", "KiB conventional RAM")
        m.line("edit test.txt")
        m.wait_for("EDIT / test.txt")
        m.text("Saved across reboot")
        m.key("ctrl-s")
        m.wait_for(" SAVED ")
        m.text(" discard")
        m.wait_for("UNSAVED")
        m.key("esc")
        m.wait_for("Discard and exit?")
        m.key("n")
        m.wait_for("EDIT / test.txt")
        m.key("esc")
        m.key("y")
        check("cat test.txt", "Saved across reboot")
        assert "discard" not in m.screen()
        check("cp test.txt copy.txt", "Saved.")
        check("cp test.txt copy.txt", "Destination exists")
        check("mv copy.txt rename.txt", "Renamed.")
        check("cat rename.txt", "Saved across reboot")
        check("rm rename.txt", "Removed.")
        check("cat rename.txt", "File not found")
        m.line("edit test.txt")
        m.wait_for("EDIT / test.txt")
        m.text("!")
        m.key("ctrl-s")
        m.wait_for(" SAVED ")
        m.key("esc")
        check("cat test.txt", "Saved across reboot!")
        m.line("edit full.txt")
        m.wait_for("EDITOR")
        m.text("z")
        m.wait_for("FILE FULL")
        m.key("esc")
        check("run hello.bf", "[Program finished]")
        assert "BFOS" in m.screen()
        check("run nested.bf", "[Program finished]")
        assert "@" in m.screen()
        check("run wrap.bf", "[Program finished]")
        assert "ABA" in m.screen()
        check("run broken.bf", "unmatched brackets")
        check("run busy.bf", "instruction limit")
        m.line("run input.bf")
        m.text("abc")
        m.key("esc")
        m.wait_for("Program cancelled")
        assert "abc" in m.screen()
        check("cat readme.txt", "VIEWER")
        m.key("spc")
        m.wait_for("Programs:")
        m.key("esc")
        m.line("clear")
        m.line("echo recall")
        m.key("up")
        m.key("ret")
        m.wait_for("recall")
        assert m.screen().count("echo recall") == 2
        m.line("clear")
        m.line("echo " + "a" * 70)
        assert "a" * 58 in m.screen() and "a" * 59 not in m.screen()
        m.line("clear")
        m.key("f1")
        m.key("ret")
        m.wait_for("FILES: ls")
        m.line("reboot")
        m.wait_for("BFOS v0.4 - raw Brainfuck workstation",timeout=60)
        m.wait_for("BFOS>",timeout=10)
        check("cat test.txt", "Saved across reboot!")
        m.screenshot(ROOT / "workstation-preview.ppm")
    assert content(image, "test.txt") == b"Saved across reboot!"
    assert content(image, "full.txt") == b"x" * 2047
    assert not any(item[1] in ("copy.txt", "rename.txt") for item in entries(image.read_bytes()))
    with Machine(image) as m:
        m.line("cat test.txt")
        m.wait_for("Saved across reboot!")
    print("PASS: files, editor, copies, rename, delete, calculator, programs, reboot persistence", flush=True)
    with Machine(image, readonly=True) as m:
        m.line("edit test.txt")
        m.wait_for("EDIT / test.txt")
        m.text(" lost")
        m.key("ctrl-s")
        m.wait_for("SAVE FAILED")
        m.key("esc")
        m.key("y")
    assert content(image, "test.txt") == b"Saved across reboot!"
    print("PASS: injected disk write failure preserves previous file", flush=True)
    for index in range(16 - len(entries(image.read_bytes()))):
        put(image, f"f{index}.txt", b"test")
    with Machine(image) as m:
        m.line("edit overflow.txt")
        m.wait_for("Directory full")
    print("PASS: directory capacity", flush=True)
    slot, _, _, bank = next(record for record in entries(image.read_bytes()) if record[1] == "test.txt")
    data = bytearray(image.read_bytes())
    data[(1 + slot*8 + bank*4)*512] ^= 1
    image.write_bytes(data)
    with Machine(image) as m:
        m.line("cat test.txt")
        m.wait_for("checksum mismatch")
    print("PASS: damaged content is rejected", flush=True)
with Machine() as m:
    m.line("ls")
    m.wait_for("Data disk missing or invalid", timeout=15)
    m.line("calc 2+3")
    m.wait_for("5")
print("PASS: missing data disk leaves shell usable")
